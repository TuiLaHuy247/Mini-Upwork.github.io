-- Mini-Upwork Phase 3 · Phần Huy (Hợp đồng, Ký quỹ Escrow, Chấm công, Hóa đơn, Thanh toán & Đánh giá)
-- Thiết kế cấu trúc Cơ sở dữ liệu (DDL - 7 bảng) theo đúng thứ tự phụ thuộc dữ liệu (Cha trước, Con sau).
-- Tương thích hoàn toàn với lược đồ miniupwork của Phase 3 & Phase 4.

BEGIN;

CREATE SCHEMA IF NOT EXISTS miniupwork;
SET search_path TO miniupwork, public;

-- =============================================================================
-- 1. BẢNG GỐC: contracts (Hợp đồng)
-- Lưu id, title, client_name, freelancer_name, contract_type ('FIXED' hoặc 'HOURLY'),
-- total_budget, hourly_rate, status, created_at.
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    client_name VARCHAR(200) NOT NULL,
    freelancer_name VARCHAR(200) NOT NULL,
    contract_type VARCHAR(10) NOT NULL,
    total_budget NUMERIC(12,2),
    hourly_rate NUMERIC(12,2),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contract_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT contract_client_not_blank CHECK (length(btrim(client_name)) > 0),
    CONSTRAINT contract_freelancer_not_blank CHECK (length(btrim(freelancer_name)) > 0),
    CONSTRAINT contract_type_valid CHECK (contract_type IN ('FIXED', 'HOURLY')),
    CONSTRAINT contract_budget_valid CHECK (total_budget IS NULL OR (total_budget > 0 AND total_budget <> 'NaN'::numeric)),
    CONSTRAINT contract_hourly_rate_valid CHECK (hourly_rate IS NULL OR (hourly_rate > 0 AND hourly_rate <> 'NaN'::numeric)),
    CONSTRAINT contract_pricing_by_type CHECK (
        (contract_type = 'FIXED' AND total_budget IS NOT NULL AND total_budget > 0)
        OR (contract_type = 'HOURLY' AND hourly_rate IS NOT NULL AND hourly_rate > 0)
    ),
    CONSTRAINT contract_status_valid CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED', 'PAUSED'))
);

-- =============================================================================
-- 2. BẢNG CỘT MỐC TRỌN GÓI: milestones
-- Gắn contract_id (FK), title, amount, due_date,
-- status ('PENDING', 'IN_PROGRESS', 'SUBMITTED', 'APPROVED').
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.contracts(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT milestone_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT milestone_amount_positive CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    CONSTRAINT milestone_status_valid CHECK (status IN ('PENDING', 'IN_PROGRESS', 'SUBMITTED', 'APPROVED'))
);

-- =============================================================================
-- 3. BẢNG TÀI KHOẢN KÝ QUỸ: escrows
-- Gắn milestone_id (FK), amount,
-- status ('UNFUNDED', 'FUNDED', 'RELEASED', 'REFUNDED'), funded_at, released_at.
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.escrows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id BIGINT NOT NULL UNIQUE REFERENCES miniupwork.milestones(id) ON DELETE RESTRICT,
    amount NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UNFUNDED',
    funded_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    CONSTRAINT escrow_amount_positive CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    CONSTRAINT escrow_status_valid CHECK (status IN ('UNFUNDED', 'FUNDED', 'RELEASED', 'REFUNDED')),
    CONSTRAINT escrow_timestamps_order CHECK (released_at IS NULL OR (funded_at IS NOT NULL AND released_at >= funded_at))
);

-- =============================================================================
-- 4. BẢNG CHẤM CÔNG THEO GIỜ: time_entries
-- Gắn contract_id (FK), invoice_id (FK — cho phép NULL), work_date, hours,
-- description, status ('PENDING', 'APPROVED').
-- Mấu chốt thiết kế: Cột invoice_id để NULL khi mới chấm công.
-- Khi xuất hóa đơn mới cập nhật ID hóa đơn vào cột này.
-- (Ràng buộc FK fk_time_entries_invoice tới bảng invoices được gắn ngay sau khi
-- bảng invoices được khởi tạo ở mục 5 để đảm bảo đúng thứ tự 1 -> 7 không lỗi FK).
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.time_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.contracts(id) ON DELETE RESTRICT,
    invoice_id BIGINT NULL,
    work_date DATE NOT NULL,
    hours NUMERIC(6,2) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT time_entry_hours_positive CHECK (hours > 0 AND hours <= 24 AND hours <> 'NaN'::numeric),
    CONSTRAINT time_entry_description_not_blank CHECK (length(btrim(description)) > 0),
    CONSTRAINT time_entry_status_valid CHECK (status IN ('PENDING', 'APPROVED'))
);

-- =============================================================================
-- 5. BẢNG HÓA ĐƠN: invoices
-- Gắn contract_id (FK), milestone_id (FK, nullable), invoice_number,
-- total_amount, issued_date, due_date, status ('DRAFT', 'SENT', 'PAID', 'PARTIAL').
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.contracts(id) ON DELETE RESTRICT,
    milestone_id BIGINT NULL REFERENCES miniupwork.milestones(id) ON DELETE RESTRICT,
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    total_amount NUMERIC(12,2) NOT NULL,
    issued_date DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT invoice_number_not_blank CHECK (length(btrim(invoice_number)) > 0),
    CONSTRAINT invoice_total_amount_positive CHECK (total_amount > 0 AND total_amount <> 'NaN'::numeric),
    CONSTRAINT invoice_dates_valid CHECK (due_date >= issued_date),
    CONSTRAINT invoice_status_valid CHECK (status IN ('DRAFT', 'SENT', 'PAID', 'PARTIAL'))
);

-- Gắn khóa ngoại từ time_entries(invoice_id) sang invoices(id) ngay sau khi bảng invoices tồn tại
ALTER TABLE miniupwork.time_entries
    DROP CONSTRAINT IF EXISTS fk_time_entries_invoice,
    ADD CONSTRAINT fk_time_entries_invoice
        FOREIGN KEY (invoice_id) REFERENCES miniupwork.invoices(id) ON DELETE SET NULL;

-- =============================================================================
-- 6. BẢNG GIAO DỊCH THANH TOÁN: payments
-- Gắn invoice_id (FK), paid_amount, payment_method,
-- status ('SUCCESS', 'FAILED', 'PENDING'), paid_at.
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES miniupwork.invoices(id) ON DELETE RESTRICT,
    paid_amount NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_amount_positive CHECK (paid_amount > 0 AND paid_amount <> 'NaN'::numeric),
    CONSTRAINT payment_method_not_blank CHECK (length(btrim(payment_method)) > 0),
    CONSTRAINT payment_status_valid CHECK (status IN ('SUCCESS', 'FAILED', 'PENDING'))
);

-- =============================================================================
-- 7. BẢNG ĐÁNH GIÁ: reviews
-- Gắn contract_id (FK), reviewer_role ('CLIENT' hoặc 'FREELANCER'),
-- rating (1 đến 5), comment, created_at.
-- =============================================================================
CREATE TABLE IF NOT EXISTS miniupwork.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES miniupwork.contracts(id) ON DELETE RESTRICT,
    reviewer_role VARCHAR(20) NOT NULL,
    rating SMALLINT NOT NULL,
    comment TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT review_role_valid CHECK (reviewer_role IN ('CLIENT', 'FREELANCER')),
    CONSTRAINT review_rating_valid CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT review_comment_not_blank CHECK (length(btrim(comment)) > 0)
);

-- =============================================================================
-- CHỈ MỤC (INDEXES) TỐI ƯU HÓA CHO 4 CÂU TRUY VẤN NGHIỆP VỤ PHASE 3
-- =============================================================================
CREATE INDEX IF NOT EXISTS ix_milestones_contract ON miniupwork.milestones(contract_id);
CREATE INDEX IF NOT EXISTS ix_milestones_overdue ON miniupwork.milestones(due_date, status) WHERE status <> 'APPROVED';
CREATE INDEX IF NOT EXISTS ix_escrows_milestone ON miniupwork.escrows(milestone_id, status);
CREATE INDEX IF NOT EXISTS ix_time_entries_contract ON miniupwork.time_entries(contract_id);
CREATE INDEX IF NOT EXISTS ix_time_entries_unbilled ON miniupwork.time_entries(contract_id, status) WHERE invoice_id IS NULL AND status = 'APPROVED';
CREATE INDEX IF NOT EXISTS ix_invoices_contract ON miniupwork.invoices(contract_id);
CREATE INDEX IF NOT EXISTS ix_payments_invoice_status ON miniupwork.payments(invoice_id, status);
CREATE INDEX IF NOT EXISTS ix_payments_paid_at_success ON miniupwork.payments(paid_at) WHERE status = 'SUCCESS';
CREATE INDEX IF NOT EXISTS ix_reviews_contract ON miniupwork.reviews(contract_id);

COMMENT ON TABLE miniupwork.contracts IS 'Bảng gốc lưu hợp đồng trọn gói (FIXED) và hợp đồng theo giờ (HOURLY).';
COMMENT ON TABLE miniupwork.milestones IS 'Các cột mốc bàn giao và nghiệm thu thuộc hợp đồng trọn gói.';
COMMENT ON TABLE miniupwork.escrows IS 'Tài khoản ký quỹ (Escrow) bảo vệ dòng tiền cho từng Milestone.';
COMMENT ON TABLE miniupwork.time_entries IS 'Bảng chấm công theo giờ; invoice_id = NULL khi chưa xuất hóa đơn.';
COMMENT ON TABLE miniupwork.invoices IS 'Hóa đơn thanh toán gắn với hợp đồng (và milestone nếu là hợp đồng trọn gói).';
COMMENT ON TABLE miniupwork.payments IS 'Lịch sử giao dịch thanh toán thực tế cho từng hóa đơn.';
COMMENT ON TABLE miniupwork.reviews IS 'Đánh giá hai chiều (1-5 sao) giữa Client và Freelancer sau nghiệm thu.';

COMMIT;
