-- Mini-Upwork Phase 3. Marketplace schema reused from Lab 2.
-- Run as the database owner in a new, dedicated database.
-- Deliberately fails if schema miniupwork exists; never resets existing data.
BEGIN;
CREATE SCHEMA miniupwork;
REVOKE ALL ON SCHEMA miniupwork FROM PUBLIC;

CREATE TABLE miniupwork.app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_email_format CHECK (email = btrim(email) AND email !~ '[[:space:]]' AND position('@' IN email) > 1),
    CONSTRAINT user_password_hash_not_blank CHECK (length(btrim(password_hash)) > 0),
    CONSTRAINT user_full_name_not_blank CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT user_status_valid CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE UNIQUE INDEX uq_app_user_email_ci ON miniupwork.app_user (lower(email));

CREATE TABLE miniupwork.client (
    user_id BIGINT PRIMARY KEY REFERENCES miniupwork.app_user(user_id) ON DELETE RESTRICT,
    company_name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    CONSTRAINT client_company_not_blank CHECK (length(btrim(company_name)) > 0),
    CONSTRAINT client_description_length CHECK (length(description) <= 10000)
);
CREATE TABLE miniupwork.freelancer (
    user_id BIGINT PRIMARY KEY REFERENCES miniupwork.app_user(user_id) ON DELETE RESTRICT,
    headline VARCHAR(200) NOT NULL,
    overview TEXT NOT NULL DEFAULT '',
    default_hourly_rate NUMERIC(12,2) NOT NULL,
    availability VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT freelancer_headline_not_blank CHECK (length(btrim(headline)) > 0),
    CONSTRAINT freelancer_overview_length CHECK (length(overview) <= 10000),
    CONSTRAINT freelancer_rate_positive CHECK (default_hourly_rate > 0 AND default_hourly_rate <> 'NaN'::numeric),
    CONSTRAINT freelancer_availability_valid CHECK (availability IN ('AVAILABLE', 'UNAVAILABLE'))
);
CREATE TABLE miniupwork.category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id BIGINT REFERENCES miniupwork.category(category_id) ON DELETE RESTRICT,
    category_name VARCHAR(100) NOT NULL,
    CONSTRAINT category_name_not_blank CHECK (category_name = btrim(category_name) AND length(category_name) > 0),
    CONSTRAINT category_not_own_parent CHECK (parent_category_id IS DISTINCT FROM category_id)
);
CREATE UNIQUE INDEX uq_category_name_ci ON miniupwork.category (lower(category_name));
CREATE TABLE miniupwork.skill (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(100) NOT NULL,
    CONSTRAINT skill_name_not_blank CHECK (skill_name = btrim(skill_name) AND length(skill_name) > 0)
);
CREATE UNIQUE INDEX uq_skill_name_ci ON miniupwork.skill (lower(skill_name));
CREATE TABLE miniupwork.freelancer_skill (
    freelancer_id BIGINT NOT NULL REFERENCES miniupwork.freelancer(user_id) ON DELETE RESTRICT,
    skill_id BIGINT NOT NULL REFERENCES miniupwork.skill(skill_id) ON DELETE RESTRICT,
    proficiency_level SMALLINT NOT NULL,
    PRIMARY KEY (freelancer_id, skill_id),
    CONSTRAINT freelancer_skill_level_valid CHECK (proficiency_level BETWEEN 1 AND 5)
);
CREATE TABLE miniupwork.job (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES miniupwork.client(user_id) ON DELETE RESTRICT,
    category_id BIGINT NOT NULL REFERENCES miniupwork.category(category_id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'DRAFT',
    job_type VARCHAR(12) NOT NULL,
    posted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT job_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT job_description_valid CHECK (length(btrim(description)) BETWEEN 1 AND 10000),
    CONSTRAINT job_status_valid CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT job_type_valid CHECK (job_type IN ('FIXED_PRICE', 'HOURLY'))
);
CREATE TABLE miniupwork.fixed_price_job (
    job_id BIGINT PRIMARY KEY REFERENCES miniupwork.job(job_id) ON DELETE RESTRICT,
    budget_amount NUMERIC(12,2) NOT NULL,
    CONSTRAINT fixed_price_budget_positive CHECK (budget_amount > 0 AND budget_amount <> 'NaN'::numeric)
);
CREATE TABLE miniupwork.hourly_job (
    job_id BIGINT PRIMARY KEY REFERENCES miniupwork.job(job_id) ON DELETE RESTRICT,
    rate_min NUMERIC(12,2) NOT NULL,
    rate_max NUMERIC(12,2) NOT NULL,
    CONSTRAINT hourly_rate_min_positive CHECK (rate_min > 0 AND rate_min <> 'NaN'::numeric),
    CONSTRAINT hourly_rate_range_valid CHECK (rate_max >= rate_min AND rate_max <> 'NaN'::numeric)
);
CREATE TABLE miniupwork.job_skill (
    job_id BIGINT NOT NULL REFERENCES miniupwork.job(job_id) ON DELETE RESTRICT,
    skill_id BIGINT NOT NULL REFERENCES miniupwork.skill(skill_id) ON DELETE RESTRICT,
    required_level SMALLINT NOT NULL,
    PRIMARY KEY (job_id, skill_id),
    CONSTRAINT job_skill_level_valid CHECK (required_level BETWEEN 1 AND 5)
);
CREATE TABLE miniupwork.proposal (
    proposal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES miniupwork.job(job_id) ON DELETE RESTRICT,
    freelancer_id BIGINT NOT NULL REFERENCES miniupwork.freelancer(user_id) ON DELETE RESTRICT,
    cover_letter TEXT NOT NULL,
    offered_amount NUMERIC(12,2) NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'SUBMITTED',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_proposal_freelancer_job UNIQUE (freelancer_id, job_id),
    CONSTRAINT proposal_cover_letter_valid CHECK (length(btrim(cover_letter)) BETWEEN 1 AND 10000),
    CONSTRAINT proposal_amount_positive CHECK (offered_amount > 0 AND offered_amount <> 'NaN'::numeric),
    CONSTRAINT proposal_status_valid CHECK (status IN ('SUBMITTED', 'WITHDRAWN'))
);

-- PK/UNIQUE keys already provide indexes; these support FK/filter access paths.
CREATE INDEX ix_category_parent ON miniupwork.category(parent_category_id);
CREATE INDEX ix_freelancer_skill_skill ON miniupwork.freelancer_skill(skill_id, freelancer_id);
CREATE INDEX ix_job_client ON miniupwork.job(client_id);
CREATE INDEX ix_job_open_category ON miniupwork.job(category_id, job_id) WHERE status = 'OPEN';
CREATE INDEX ix_job_open_type ON miniupwork.job(job_type, job_id) WHERE status = 'OPEN';
CREATE INDEX ix_job_skill_skill ON miniupwork.job_skill(skill_id, job_id);
CREATE INDEX ix_proposal_job ON miniupwork.proposal(job_id, proposal_id);

-- Trigger functions have a fixed search_path. All application SQL stays qualified.
CREATE FUNCTION miniupwork.keep_identifiers_immutable()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE column_name TEXT;
BEGIN
    FOREACH column_name IN ARRAY TG_ARGV LOOP
        IF (to_jsonb(NEW) -> column_name) IS DISTINCT FROM (to_jsonb(OLD) -> column_name) THEN
            RAISE EXCEPTION '% cannot be changed', column_name
                USING ERRCODE = '23514', CONSTRAINT = 'immutable_identifier';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_10_user_immutable BEFORE UPDATE ON miniupwork.app_user FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('user_id');
CREATE TRIGGER trg_10_client_immutable BEFORE UPDATE ON miniupwork.client FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('user_id');
CREATE TRIGGER trg_10_freelancer_immutable BEFORE UPDATE ON miniupwork.freelancer FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('user_id');
CREATE TRIGGER trg_10_category_immutable BEFORE UPDATE ON miniupwork.category FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('category_id');
CREATE TRIGGER trg_10_skill_immutable BEFORE UPDATE ON miniupwork.skill FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('skill_id');
CREATE TRIGGER trg_10_freelancer_skill_immutable BEFORE UPDATE ON miniupwork.freelancer_skill FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('freelancer_id', 'skill_id');
CREATE TRIGGER trg_10_job_immutable BEFORE UPDATE ON miniupwork.job FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('job_id', 'client_id', 'job_type');
CREATE TRIGGER trg_10_fixed_job_immutable BEFORE UPDATE ON miniupwork.fixed_price_job FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('job_id');
CREATE TRIGGER trg_10_hourly_job_immutable BEFORE UPDATE ON miniupwork.hourly_job FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('job_id');
CREATE TRIGGER trg_10_job_skill_immutable BEFORE UPDATE ON miniupwork.job_skill FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('job_id', 'skill_id');
CREATE TRIGGER trg_10_proposal_immutable BEFORE UPDATE ON miniupwork.proposal FOR EACH ROW EXECUTE FUNCTION miniupwork.keep_identifiers_immutable('proposal_id', 'job_id', 'freelancer_id');

CREATE FUNCTION miniupwork.guard_category_tree()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
BEGIN
    -- Serializes hierarchy edits, including concurrent attempts at cross-links.
    PERFORM pg_advisory_xact_lock(791028, 1);
    IF NEW.parent_category_id IS NOT NULL AND EXISTS (
        WITH RECURSIVE ancestors(category_id, parent_category_id) AS (
            SELECT c.category_id, c.parent_category_id FROM miniupwork.category c WHERE c.category_id = NEW.parent_category_id
            UNION
            SELECT c.category_id, c.parent_category_id FROM miniupwork.category c JOIN ancestors a ON c.category_id = a.parent_category_id
        )
        SELECT 1 FROM ancestors WHERE category_id = NEW.category_id
    ) THEN
        RAISE EXCEPTION 'A category hierarchy cannot contain a cycle'
            USING ERRCODE = '23514', CONSTRAINT = 'category_cycle';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_20_category_tree BEFORE INSERT OR UPDATE ON miniupwork.category FOR EACH ROW EXECUTE FUNCTION miniupwork.guard_category_tree();

-- Common-user locks serialize mutations of its two different profile relations.
CREATE FUNCTION miniupwork.lock_profile_user()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE target_id BIGINT;
BEGIN
    target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.user_id ELSE NEW.user_id END;
    PERFORM 1 FROM miniupwork.app_user WHERE user_id = target_id FOR UPDATE;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_20_client_lock BEFORE INSERT OR UPDATE OR DELETE ON miniupwork.client FOR EACH ROW EXECUTE FUNCTION miniupwork.lock_profile_user();
CREATE TRIGGER trg_20_freelancer_lock BEFORE INSERT OR UPDATE OR DELETE ON miniupwork.freelancer FOR EACH ROW EXECUTE FUNCTION miniupwork.lock_profile_user();

CREATE FUNCTION miniupwork.check_user_profile_complete()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE target_id BIGINT;
BEGIN
    target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.user_id ELSE NEW.user_id END;
    IF EXISTS (SELECT 1 FROM miniupwork.app_user WHERE user_id = target_id)
       AND NOT EXISTS (SELECT 1 FROM miniupwork.client WHERE user_id = target_id)
       AND NOT EXISTS (SELECT 1 FROM miniupwork.freelancer WHERE user_id = target_id) THEN
        RAISE EXCEPTION 'Every user requires a client profile, a freelancer profile, or both'
            USING ERRCODE = '23514', CONSTRAINT = 'user_profile_complete';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_user_profile_complete AFTER INSERT OR UPDATE ON miniupwork.app_user DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_user_profile_complete();
CREATE CONSTRAINT TRIGGER ct_client_profile_complete AFTER INSERT OR UPDATE OR DELETE ON miniupwork.client DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_user_profile_complete();
CREATE CONSTRAINT TRIGGER ct_freelancer_profile_complete AFTER INSERT OR UPDATE OR DELETE ON miniupwork.freelancer DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_user_profile_complete();

CREATE FUNCTION miniupwork.guard_job_lifecycle()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.status <> 'DRAFT' THEN
        RAISE EXCEPTION 'A new job starts in DRAFT'
            USING ERRCODE = '23514', CONSTRAINT = 'job_initial_status';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status THEN
        IF NOT ((OLD.status = 'DRAFT' AND NEW.status IN ('OPEN', 'CANCELLED'))
             OR (OLD.status = 'OPEN' AND NEW.status IN ('CLOSED', 'CANCELLED'))) THEN
            RAISE EXCEPTION 'The requested job status transition is not allowed'
                USING ERRCODE = '23514', CONSTRAINT = 'job_invalid_transition';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_20_job_lifecycle BEFORE INSERT OR UPDATE ON miniupwork.job FOR EACH ROW EXECUTE FUNCTION miniupwork.guard_job_lifecycle();

CREATE FUNCTION miniupwork.lock_and_guard_job_child()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE target_id BIGINT; parent_type TEXT;
BEGIN
    target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.job_id ELSE NEW.job_id END;
    SELECT job_type INTO parent_type FROM miniupwork.job WHERE job_id = target_id FOR UPDATE;
    -- An absent parent is reported by its ordinary FK, SQLSTATE 23503.
    IF TG_OP <> 'DELETE' AND parent_type IS NOT NULL
       AND ((TG_TABLE_NAME = 'fixed_price_job' AND parent_type <> 'FIXED_PRICE')
         OR (TG_TABLE_NAME = 'hourly_job' AND parent_type <> 'HOURLY')) THEN
        RAISE EXCEPTION 'Job pricing subtype must match job_type'
            USING ERRCODE = '23514', CONSTRAINT = 'job_subtype_matches_type';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_20_fixed_job_lock BEFORE INSERT OR UPDATE OR DELETE ON miniupwork.fixed_price_job FOR EACH ROW EXECUTE FUNCTION miniupwork.lock_and_guard_job_child();
CREATE TRIGGER trg_20_hourly_job_lock BEFORE INSERT OR UPDATE OR DELETE ON miniupwork.hourly_job FOR EACH ROW EXECUTE FUNCTION miniupwork.lock_and_guard_job_child();
CREATE TRIGGER trg_20_job_skill_lock BEFORE INSERT OR UPDATE OR DELETE ON miniupwork.job_skill FOR EACH ROW EXECUTE FUNCTION miniupwork.lock_and_guard_job_child();

CREATE FUNCTION miniupwork.check_job_complete()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE target_id BIGINT; parent_type TEXT; parent_status TEXT; has_fixed BOOLEAN; has_hourly BOOLEAN;
BEGIN
    target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.job_id ELSE NEW.job_id END;
    SELECT job_type, status INTO parent_type, parent_status FROM miniupwork.job WHERE job_id = target_id;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT EXISTS (SELECT 1 FROM miniupwork.fixed_price_job WHERE job_id = target_id),
           EXISTS (SELECT 1 FROM miniupwork.hourly_job WHERE job_id = target_id)
      INTO has_fixed, has_hourly;
    IF has_fixed IS DISTINCT FROM (parent_type = 'FIXED_PRICE')
       OR has_hourly IS DISTINCT FROM (parent_type = 'HOURLY') THEN
        RAISE EXCEPTION 'Every job requires exactly its matching pricing subtype'
            USING ERRCODE = '23514', CONSTRAINT = 'job_subtype_complete';
    END IF;
    IF parent_status = 'OPEN' AND NOT EXISTS (SELECT 1 FROM miniupwork.job_skill WHERE job_id = target_id) THEN
        RAISE EXCEPTION 'An OPEN job requires at least one skill'
            USING ERRCODE = '23514', CONSTRAINT = 'job_requires_skill';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_job_complete AFTER INSERT OR UPDATE ON miniupwork.job DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_job_complete();
CREATE CONSTRAINT TRIGGER ct_fixed_job_complete AFTER INSERT OR UPDATE OR DELETE ON miniupwork.fixed_price_job DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_job_complete();
CREATE CONSTRAINT TRIGGER ct_hourly_job_complete AFTER INSERT OR UPDATE OR DELETE ON miniupwork.hourly_job DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_job_complete();
CREATE CONSTRAINT TRIGGER ct_job_skill_complete AFTER INSERT OR UPDATE OR DELETE ON miniupwork.job_skill DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION miniupwork.check_job_complete();

CREATE FUNCTION miniupwork.guard_proposal_lifecycle()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, miniupwork AS $$
DECLARE parent_status TEXT; owner_id BIGINT; is_resubmit BOOLEAN := FALSE;
BEGIN
    -- Close/open and skill/subtype mutations acquire this same job-row lock.
    SELECT status, client_id INTO parent_status, owner_id FROM miniupwork.job WHERE job_id = NEW.job_id FOR UPDATE;
    IF TG_OP = 'INSERT' AND NEW.status <> 'SUBMITTED' THEN
        RAISE EXCEPTION 'A new proposal starts in SUBMITTED'
            USING ERRCODE = '23514', CONSTRAINT = 'proposal_initial_status';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        is_resubmit := OLD.status = 'WITHDRAWN' AND NEW.status = 'SUBMITTED';
        IF NOT (is_resubmit OR (OLD.status = 'SUBMITTED' AND NEW.status = 'WITHDRAWN')) THEN
            RAISE EXCEPTION 'Only withdrawal or resubmission is supported in this lab slice'
                USING ERRCODE = '23514', CONSTRAINT = 'proposal_invalid_transition';
        END IF;
        IF NOT is_resubmit AND (NEW.cover_letter IS DISTINCT FROM OLD.cover_letter
            OR NEW.offered_amount IS DISTINCT FROM OLD.offered_amount
            OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at) THEN
            RAISE EXCEPTION 'Withdrawal changes only the proposal status'
                USING ERRCODE = '23514', CONSTRAINT = 'proposal_withdraw_changes';
        END IF;
    END IF;
    IF owner_id = NEW.freelancer_id THEN
        RAISE EXCEPTION 'A user cannot submit a proposal to their own job'
            USING ERRCODE = '23514', CONSTRAINT = 'proposal_self_bid';
    END IF;
    IF (TG_OP = 'INSERT' OR is_resubmit) AND parent_status IS NOT NULL AND parent_status <> 'OPEN' THEN
        RAISE EXCEPTION 'Only OPEN jobs accept new or resubmitted proposals'
            USING ERRCODE = '23514', CONSTRAINT = 'proposal_requires_open_job';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_20_proposal_lifecycle BEFORE INSERT OR UPDATE ON miniupwork.proposal FOR EACH ROW EXECUTE FUNCTION miniupwork.guard_proposal_lifecycle();

